 const db = new PGlite();
 await db.exec(`create role anon; create role authenticated;
 create schema auth; create schema storage;
 create table auth.users(id uuid primary key);
 insert into auth.users values ('11111111-1111-1111-1111-111111111111'),('22222222-2222-2222-2222-222222222222');
 create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 grant usage on schema auth,storage,public to anon,authenticated;
 grant execute on function auth.uid() to anon,authenticated;
 create table storage.buckets(id text primary key,name text,public boolean,file_size_limit bigint,allowed_mime_types text[]);
 create table storage.objects(id serial primary key,bucket_id text,name text);
 alter table storage.objects enable row level security;
 create policy unrelated_broad_policy on storage.objects for all to anon,authenticated using(true) with check(true);
 grant select,insert,update,delete on storage.objects to anon,authenticated;
 grant usage on sequence storage.objects_id_seq to anon,authenticated;`);
 await db.exec(fs.readFileSync(path.join(__dirname,'../supabase/migrations/20260907_personal_workspace.sql'),'utf8'));
 const userA='11111111-1111-1111-1111-111111111111', userB='22222222-2222-2222-2222-222222222222';
 const note='33333333-3333-3333-3333-333333333333', pdf='44444444-4444-4444-4444-444444444444';
