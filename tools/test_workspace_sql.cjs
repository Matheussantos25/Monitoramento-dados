 await assert.rejects(db.query("insert into public.solem_items(id,kind,title,body) values ('55555555-5555-5555-5555-555555555555','mindmap','Mapa',E'Raiz\\n    Salto')"));
 await asUser(userB);
 assert.equal((await db.query('select * from public.solem_items')).rows.length,0);
 assert.equal((await db.query('select * from storage.objects')).rows.length,0);
